export async function seedExtras(companyId: string) {
  const now = Date.now();
  await Promise.all([
    supabase.from("channel_connections").insert(
      CHANNELS.map((c) => ({
        ...c,
        company_id: companyId,
        last_sync: new Date(now - 1000 * 60 * 12).toISOString(),
      })),
    ),
    supabase.from("channel_posts").insert(
      POSTS.map(([provider, body, status, impressions, likes, reposts, agent_name], i) => ({
        company_id: companyId,
        provider,
        body,
        status,
        impressions,
        likes,
        reposts,
        agent_name,
        scheduled_at:
          status === "scheduled" ? new Date(now + 3600_000 * (i + 2)).toISOString() : null,
        created_at: new Date(now - i * 3600_000 * 7).toISOString(),
      })),
    ),
    supabase.from("trades").insert(
      TRADES.map(
        ([symbol, side, size, entry, exitPrice, pnl, confidence, status, rationale], i) => ({
          company_id: companyId,
          symbol,
          side,
          size,
          entry,
          exit: exitPrice,
          pnl,
          confidence,
          status,
          rationale,
          opened_at: new Date(now - (i + 1) * 3600_000 * 11).toISOString(),
          closed_at: status === "closed" ? new Date(now - i * 3600_000 * 4).toISOString() : null,
        }),
      ),
    ),
    supabase.from("community_posts").insert(
      COMMUNITY.map(
        ([author_name, author_role, avatar, topic, body, likes, replies, pinned], i) => ({
          company_id: companyId,
          author_name,
          author_role,
          avatar,
          topic,
          body,
          likes,
          replies,
          pinned,
          created_at: new Date(now - i * 3600_000 * 5).toISOString(),
        }),
      ),
    ),
    supabase.from("founder_progress").insert({
      company_id: companyId,
      xp: 120,
      level: 1,
      streak_days: 1,
      seat_number: 1200 + Math.floor(Math.random() * 180),
    }),
  ]);
}
